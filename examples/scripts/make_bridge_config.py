#!/usr/bin/env python3
"""Write a bridge config with one device per emulator port.

Each device gets the variables of the first device of the same kind in a
template config (default: examples/bridge-varying.yaml), so the variable set
follows the maintained example.

usage:
  python examples/scripts/make_bridge_config.py --kind wib --ports 1234-1263 -o bridge-wibs.yaml
  python examples/scripts/make_bridge_config.py --kind wib --ports 1234,1240-1242 --period 5

Then run the bridge with:
  uv run python -m dune_dscs.bridge bridge-wibs.yaml
"""

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DEFAULT_TEMPLATE = HERE.parent / "bridge-varying.yaml"
SCHEME = {"wib": "tcp", "daphne": "tcp", "pdu": "udp"}


def parse_ports(text):
    """'1234-1236,1240' -> [1234, 1235, 1236, 1240]"""
    ports = []
    for part in text.split(","):
        first, _, last = part.strip().partition("-")
        first, last = int(first), int(last or first)
        if not 1 <= first <= last <= 65535:
            raise argparse.ArgumentTypeError(f"bad port range: {part!r}")
        ports.extend(range(first, last + 1))
    if len(set(ports)) != len(ports):
        raise argparse.ArgumentTypeError("ports repeat")
    return ports


def template_device(template, kind):
    for device in template.get("devices", []):
        if device.get("kind") == kind:
            return device
    sys.exit(f"no '{kind}' device in the template config to copy variables from")


def make_config(template, kind, ports, host, endpoint=None, period=None, timeout=None):
    base = template_device(template, kind)
    width = max(3, len(str(len(ports))))
    devices = []
    for number, port in enumerate(ports, start=1):
        device = {"id": f"{kind}-{number:0{width}d}", "kind": kind,
                  "endpoint": f"{SCHEME[kind]}://{host}:{port}"}
        for key in ("community", "period"):  # keep the template's optional settings
            if key in base:
                device[key] = base[key]
        if period is not None:
            device["period"] = period
        device["variables"] = base["variables"]
        devices.append(device)

    config = {key: template[key] for key in ("endpoint", "timeout", "concurrency") if key in template}
    if endpoint:
        config["endpoint"] = endpoint
    if timeout is not None:
        config["timeout"] = timeout
    config["devices"] = devices
    return config


class _Dumper(yaml.SafeDumper):
    """Write each variable on one line, like the hand-written examples."""


def _flow_variable(dumper, data):
    flow = "source" in data  # variables are {source: ..., type: ...}
    return dumper.represent_mapping("tag:yaml.org,2002:map", data, flow_style=flow)


_Dumper.add_representer(dict, _flow_variable)
_Dumper.ignore_aliases = lambda self, data: True  # repeat variables instead of &anchors


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kind", required=True, choices=sorted(SCHEME))
    parser.add_argument("--ports", required=True, type=parse_ports, help="e.g. 1234-1263 or 1234,1240-1242")
    parser.add_argument("--host", default="127.0.0.1",
                        help="emulator address; 0.0.0.0 is written as 127.0.0.1 (default %(default)s)")
    parser.add_argument("--endpoint", help="OPC UA endpoint the bridge serves (default: template's)")
    parser.add_argument("--period", type=float, help="poll interval in seconds (default: template's, else 1)")
    parser.add_argument("--timeout", type=float, help="per-read timeout in seconds (default: template's)")
    parser.add_argument("--template", type=Path, default=DEFAULT_TEMPLATE,
                        help="config to copy variables from (default %(default)s)")
    parser.add_argument("-o", "--output", type=Path, help="output file (default: stdout)")
    args = parser.parse_args()

    template = yaml.safe_load(args.template.read_text()) or {}
    host = "127.0.0.1" if args.host == "0.0.0.0" else args.host  # 0.0.0.0 binds, it is not a destination
    config = make_config(template, args.kind, args.ports, host, args.endpoint, args.period, args.timeout)
    text = (f"# Generated by {Path(__file__).name}: {len(args.ports)} {args.kind} device(s),"
            f" variables from {args.template.name}.\n")
    text += yaml.dump(config, Dumper=_Dumper, sort_keys=False, width=120)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
        print(f"wrote {args.output} ({len(args.ports)} {args.kind} devices)", file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
